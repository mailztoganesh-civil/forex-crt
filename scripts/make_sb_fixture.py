"""Build forex/tests/sb_fixture.json: real New York days (00:00-16:00, 5-minute bars from forex-data) with the Silver Bullet
results of scripts/silver_bullet_backtest.py (day_setup + trade, no costs). forex/tests/run_tests.js runs forex/sb.js on the
same candles and must get the same setup and the same trade outcome for every entry / target rule.
Usage: python scripts/make_sb_fixture.py <forex-data checkout>"""
import json, os, sys
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import silver_bullet_backtest as S   # noqa: E402

OUT = os.path.join(HERE, "..", "forex", "tests", "sb_fixture.json")
PICK = {"NSXUSD": 70, "EURUSD": 50, "XAUUSD": 40}      # days per symbol (all setup days first, then others), 2026


def main(root):
    days = []
    for sym, cap in PICK.items():
        df = S.load(root, sym); ny = df.index.tz_convert("America/New_York")
        dg = 2 if sym != "EURUSD" else 5
        withs, without = [], []
        for day, idx in pd.Series(np.arange(len(df)), index=ny).groupby(ny.date):
            if str(day) < "2026-01-01": continue
            a = idx.values; mins = np.array([S.hm(t) for t in ny[a]])
            keep = a[mins <= 955]; mins = mins[mins <= 955]
            if len(keep) < 150 or mins[-1] != 955: continue
            T = df.index[keep]; O, H, L, C = (np.round(df[c].values[keep], dg) for c in ("Open", "High", "Low", "Close"))
            s = S.day_setup(T, O, H, L, C, mins, day)
            exp = {"setup": None if s is None else "both" if s == "both" else {k: (float(v) if isinstance(v, (float, np.floating)) else v) for k, v in s.items()}, "trades": {}}
            if isinstance(s, dict):
                for ek in S.ENTRIES:
                    for tm in ("dol", "2R"):
                        r = S.trade(s, T, O, H, L, C, mins, ek, tm, 0.0, 0.0)
                        exp["trades"][f"{ek}|{tm}"] = None if r is None else {k: (float(v) if isinstance(v, (float, np.floating)) else v) for k, v in r.items()}
            rec = {"sym": sym, "day": str(day), "c": [[int(t.timestamp()), float(o), float(h), float(l), float(c)] for t, o, h, l, c in zip(T, O, H, L, C)], "expect": exp}
            (withs if isinstance(s, dict) else without).append(rec)
        sel = withs[:cap] + without[:max(0, cap - len(withs))]
        days += sel
        print(sym, "days with a setup:", len(withs), "kept", len(sel))
    json.dump({"note": "generated by scripts/make_sb_fixture.py", "days": days}, open(OUT, "w"))
    print("wrote", OUT, os.path.getsize(OUT) // 1024, "KB")


if __name__ == "__main__":
    main(sys.argv[1])
